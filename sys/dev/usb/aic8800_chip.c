/*
 * AIC8800D80 chip layer -- lmac_msg command framing, the firmware
 * download state machine, and the connect/scan/key command set.
 *
 * The protocol facts (frame layout, command IDs, RAM addresses, the
 * 1 KiB block-write rule) are transcribed from the vendor SDK
 * (os/aic8800) per the AIC8800D80 ground truth; this file is a native
 * implementation, not a translation of GPL source.
 */

#include <sys/cdefs.h>
__KERNEL_RCSID(0, "$NetBSD$");

#include <sys/param.h>
#include <sys/systm.h>
#include <sys/device.h>

#include "aic8800var.h"

const char *
aic8800u_personality_name(enum aic8800u_personality personality)
{
	switch (personality) {
	case AIC8800U_BROM:
		return "boot ROM";
	case AIC8800U_APP:
		return "app";
	}
	return "unknown";
}
